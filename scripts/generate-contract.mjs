import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const output = fileURLToPath(
  new URL("apps/console/public/v20/api/contract.generated.js", root),
);

export async function renderContract() {
  const definitions = await readFile(
    new URL("packages/contract/src/console-p1.mjs", root),
    "utf8",
  );
  const validation = await readFile(
    new URL("packages/contract/src/validate.mjs", root),
    "utf8",
  );
  const dependency = 'import { operations } from "./console-p1.mjs";\n';
  if (!validation.startsWith(dependency))
    throw new Error("Unsupported contract dependency");
  return (
    "// Generated by scripts/generate-contract.mjs. Do not edit.\n" +
    definitions.trimEnd() +
    "\n\n" +
    validation.slice(dependency.length).trimStart()
  );
}

export async function checkContract(path = output) {
  if ((await readFile(path, "utf8")) !== (await renderContract()))
    throw new Error(
      "Browser contract is out of date; run node scripts/generate-contract.mjs",
    );
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length && args[0] !== "--check"))
    throw new Error("Use --check or no arguments");
  if (args[0] === "--check") await checkContract();
  else {
    await mkdir(dirname(output), { recursive: true });
    await writeFile(output, await renderContract());
  }
  console.log(
    args[0] === "--check"
      ? "Browser contract is current."
      : "Browser contract generated.",
  );
}
